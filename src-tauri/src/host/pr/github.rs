    #[test]
    fn one_document_asks_about_every_linked_pr_and_interpolates_nothing() {
        let query = build_query(&keys());
        assert!(query.document.contains("pr0: repository(owner: $owner0"));
        assert!(query.document.contains("pr2: repository(owner: $owner2"));
        assert!(query.document.contains("fragment PrFields on PullRequest"));
        // The repository names are variables, never text in the document: a
        // repo called `x") { ... }` must not be able to write the query.
        assert!(!query.document.contains("jabreeflor"));
        assert!(!query.document.contains("globnet-sync"));
        assert_eq!(query.variables.len(), 9);
        assert_eq!(
            query.variables[0],
            ("owner0".to_string(), "jabreeflor".to_string())
        );
        assert_eq!(
            query.variables[2],
            ("number0".to_string(), "23".to_string())
        );
    }

